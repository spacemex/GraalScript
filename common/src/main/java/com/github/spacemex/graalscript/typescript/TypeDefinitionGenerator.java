package com.github.spacemex.graalscript.typescript;

import com.github.spacemex.graalscript.api.annotation.ScriptCallback;
import com.github.spacemex.graalscript.api.annotation.ScriptMethod;
import com.github.spacemex.graalscript.api.annotation.ScriptType;
import com.github.spacemex.graalscript.runtime.ScriptScope;
import org.graalvm.polyglot.Value;

import java.io.IOException;
import java.lang.reflect.Method;
import java.lang.reflect.Parameter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.Arrays;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.Map;

public final class TypeDefinitionGenerator {

    private TypeDefinitionGenerator() {
    }

    public static void generate(Path root, ScriptScope scope, Map<String, Object> bindings) throws IOException {

        Path output = root.resolve("generated")
                .resolve(scope.getDirectory() + ".d.ts");

        Files.createDirectories(output.getParent());

        StringBuilder builder = new StringBuilder();

        builder.append("// Generated by Graal Script.\n");
        builder.append("// Do not edit manually.\n\n");

        Map<String, Class<?>> eventTypes = new LinkedHashMap<>();

        for (Object instance : bindings.values()) {
            for (Method method : instance.getClass().getMethods()) {

                if (!method.isAnnotationPresent(ScriptMethod.class)) {
                    continue;
                }

                // Discover callback parameter types.
                ScriptCallback callback =
                        method.getAnnotation(ScriptCallback.class);

                if (callback != null) {
                    registerScriptType(
                            eventTypes,
                            callback.value()
                    );
                }

                // Discover annotated Java return types.
                Class<?> returnType = method.getReturnType();

                if (returnType.isAnnotationPresent(ScriptType.class)) {
                    registerScriptType(
                            eventTypes,
                            returnType
                    );
                }
            }
        }

        // Generate interfaces for discovered event objects.
        for (Map.Entry<String, Class<?>> entry :
                eventTypes.entrySet()) {

            builder.append("interface ")
                    .append(entry.getKey())
                    .append(" {\n");

            appendMethods(builder, entry.getValue());

            builder.append("}\n\n");
        }

        // Generate global script API declarations.
        for (Map.Entry<String, Object> entry :
                bindings.entrySet()) {

            builder.append("declare const ")
                    .append(entry.getKey())
                    .append(": {\n");

            appendMethods(builder, entry.getValue().getClass());

            builder.append("};\n\n");
        }

        Files.writeString(
                output,
                builder.toString(),
                StandardCharsets.UTF_8,
                StandardOpenOption.CREATE,
                StandardOpenOption.TRUNCATE_EXISTING
        );
    }

    private static String mapType(Class<?> type) {
        if (type.isAnnotationPresent(ScriptType.class)) {
            return getScriptTypeName(type);
        }

        if (type == void.class || type == Void.class) {
            return "void";
        }
        if (type == String.class || type == char.class || type == Character.class || CharSequence.class.isAssignableFrom(type)) {
            return "string";
        }
        if (type == boolean.class || type == Boolean.class) {
            return "boolean";
        }
        if (type.isPrimitive() || Number.class.isAssignableFrom(type)) {
            return "number";
        }
        if (type == byte.class || type == Byte.class || type == short.class || type == Short.class || type == int.class ||
                type == Integer.class || type == long.class || type == Long.class || type == float.class || type == Float.class
                || type == double.class || type == Double.class) {
            return "number";
        }
        if (type.isArray()) {
            return mapType(type.getComponentType()) + "[]";
        }
        return "unknown";
    }


    private static void appendMethods(
            StringBuilder builder,
            Class<?> type
    ) {
        Method[] methods = type.getMethods();

        Arrays.sort(
                methods,
                Comparator.comparing(Method::getName)
                        .thenComparing(Method::toString)
        );

        for (Method method : methods) {
            ScriptMethod scriptMethod =
                    method.getAnnotation(ScriptMethod.class);

            if (scriptMethod == null) {
                continue;
            }

            if (!scriptMethod.description().isBlank()) {
                String description = scriptMethod.description()
                        .replace("*/", "* /")
                        .replace("\r", " ")
                        .replace("\n", " ");

                builder.append("  /** ")
                        .append(description)
                        .append(" */\n");
            }

            builder.append("  ")
                    .append(method.getName())
                    .append("(");

            ScriptCallback callback =
                    method.getAnnotation(ScriptCallback.class);

            if (callback != null) {
                Parameter[] parameters = method.getParameters();

                if (parameters.length != 1 ||
                        parameters[0].getType() != Value.class) {
                    throw new IllegalStateException(
                            "@ScriptCallback requires one Value parameter: " +
                                    method
                    );
                }

                String eventType =
                        getScriptTypeName(callback.value());

                builder.append("listener: (event: ")
                        .append(eventType)
                        .append(") => void");

            } else {
                Parameter[] parameters = method.getParameters();

                for (int i = 0; i < parameters.length; i++) {
                    if (i > 0) {
                        builder.append(", ");
                    }

                    Parameter parameter = parameters[i];

                    String name = parameter.isNamePresent()
                            ? parameter.getName()
                            : "arg" + i;

                    builder.append(name)
                            .append(": ")
                            .append(mapType(parameter.getType()));
                }
            }

            builder.append("): ")
                    .append(mapType(method.getReturnType()))
                    .append(";\n");
        }
    }

    private static String getScriptTypeName(Class<?> type) {
        ScriptType annotation =
                type.getAnnotation(ScriptType.class);

        if (annotation == null) {
            throw new IllegalArgumentException(
                    type.getName() + " is missing @ScriptType"
            );
        }

        String name = annotation.name();

        if (!name.matches("[A-Za-z_$][A-Za-z0-9_$]*")) {
            throw new IllegalArgumentException(
                    "Invalid script type name: " + name
            );
        }

        return name;
    }

    private static void registerScriptType(
            Map<String, Class<?>> types,
            Class<?> javaType
    ) {
        String typeName = getScriptTypeName(javaType);

        Class<?> existing =
                types.putIfAbsent(typeName, javaType);

        if (existing != null && existing != javaType) {
            throw new IllegalStateException(
                    "Conflicting TypeScript type: " + typeName
            );
        }
    }
}
